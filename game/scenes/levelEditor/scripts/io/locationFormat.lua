-- The `.katsa` location data: version check, the node tree encoder/decoder and the package
-- file set (settings.lua, main.lua, assets/location.lua, copied assets). Engine access goes
-- through an adapter, so this module stays pure and testable.
--
-- Adapter for encode:  adapter.className(node), adapter.name(node), adapter.properties(node),
--                      adapter.children(node); optional adapter.attributes(node) and
--                      adapter.model(node) (a model node keeps its file instead of its meshes)
-- Builder for decode:  builder.create(class, name, properties, parentHandle, entry) -> handle
local LuaText = require('./luaText')
local ZipWriter = require('./zipWriter')

local Format = {}

Format.NAME = 'katsa-location'
Format.VERSION = 1

local LOADER = [[
-- Generated by the Katsa level editor. Loads assets/location.lua into the scene's world.
local Scene = {}

function Scene.create(scene, context)
    local Loader = context:require('scripts.loader')
    return Loader.create(scene, context)
end

return Scene
]]

local SETTINGS = [[
return {
    layoutVersion = 3,
    presentation = { navigation = false },
}
]]

local function encodeNode(node, adapter)
    local result = {
        class = adapter.className(node),
        name = adapter.name(node),
        properties = adapter.properties(node),
        attributes = adapter.attributes and adapter.attributes(node) or nil,
        model = adapter.model and adapter.model(node) or nil,
        children = {},
    }
    for index, child in ipairs(adapter.children(node)) do
        result.children[index] = encodeNode(child, adapter)
    end
    return result
end

-- Returns the data table for a list of root nodes.
function Format.encode(roots, adapter)
    local nodes = {}
    for index, node in ipairs(roots) do
        nodes[index] = encodeNode(node, adapter)
    end
    return { format = Format.NAME, version = Format.VERSION, nodes = nodes }
end

-- Returns data or nil plus a readable message. Never throws on bad input.
function Format.check(data)
    if type(data) ~= 'table' or data.format ~= Format.NAME then
        return nil, 'Not a Katsa location file'
    end
    if type(data.version) ~= 'number' then
        return nil, 'The location file has no version'
    end
    if data.version > Format.VERSION or data.version < 1 then
        return nil,
            ('Unsupported location version %s (this editor reads %d)'):format(
                tostring(data.version),
                Format.VERSION
            )
    end
    if type(data.nodes) ~= 'table' then
        return nil, 'The location file has no node list'
    end
    return data
end

local function decodeNode(entry, builder, parent, count)
    assert(type(entry) == 'table' and type(entry.class) == 'string', 'Corrupt node entry')
    local handle = builder.create(entry.class, entry.name, entry.properties or {}, parent, entry)
    count = count + 1
    for _, child in ipairs(entry.children or {}) do
        count = decodeNode(child, builder, handle, count)
    end
    return count
end

-- Builds every node through `builder`. Returns the number of nodes, or nil plus a message.
function Format.decode(data, builder)
    local checked, message = Format.check(data)
    if not checked then
        return nil, message
    end
    local count = 0
    for _, entry in ipairs(checked.nodes) do
        count = decodeNode(entry, builder, nil, count)
    end
    return count
end

-- Parses text from assets/location.lua and checks it.
function Format.parse(text)
    local data, message = LuaText.parse(text, 'location.lua')
    if not data then
        return nil, 'Cannot read the location file: ' .. tostring(message)
    end
    return Format.check(data)
end

-- Builds the archive text. `files` maps package paths (assets/...) to bytes; `loaderSource` is
-- the scripts/loader.lua text the package carries so it can run on its own.
function Format.pack(data, files, loaderSource)
    local zip = ZipWriter.new()
    zip:add('settings.lua', SETTINGS)
    zip:add('main.lua', LOADER)
    zip:addDirectory('assets')
    zip:add('assets/location.lua', LuaText.serialize(data))
    zip:addDirectory('scripts')
    zip:add('scripts/loader.lua', loaderSource or '')
    local names = {}
    for name in pairs(files or {}) do
        names[#names + 1] = name
    end
    table.sort(names)
    for _, name in ipairs(names) do
        zip:add(name, files[name])
    end
    return zip:build()
end

return Format
