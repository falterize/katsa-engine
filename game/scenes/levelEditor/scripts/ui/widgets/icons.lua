-- Redo is undo mirrored; building it from the same art keeps the two always matching.
local function flip(rows)
    local result = {}
    for index, row in ipairs(rows) do
        result[index] = row:reverse()
    end
    return result
end

ART.redo = flip(ART.undo)

local cache = {}

function Icons.names()
    local list = {}
    for name in pairs(ART) do
        list[#list + 1] = name
    end
    table.sort(list)
    return list
end

-- The shared image for `name` (a katsa image), or nil for an unknown name.
function Icons.image(name)
    local image = cache[name]
    if image then
        return image
    end
    local rows = ART[name]
    if not rows then
        return nil
    end
    local data = katsa.image.newImageData(SIZE, SIZE)
    data:mapPixel(function(x, y)
        local row = rows[y + 1]
        if row and row:sub(x + 1, x + 1) == '#' then
            return 1, 1, 1, 1
        end
        return 1, 1, 1, 0
    end)
    image = katsa.graphics.newImage(data)
    image:setFilter('nearest', 'nearest')
    data:release()
    cache[name] = image
    return image
end

Icons.SIZE = SIZE

-- Adds an icon to `parent` at pixel position (x, y), drawn `size` pixels wide (a whole multiple
-- of 16 stays sharp). Returns the ImageRect.
function Icons.add(ui, parent, name, x, y, size)
    size = size or SIZE
    return Kit.make(ui, 'ImageRect', {
        position = { 0, x, 0, y },
        size = { 0, size, 0, size },
        image = Icons.image(name),
        fitMode = 'Fit',
        pixelate = true,
        backgroundTransparency = 1,
        interactable = false,
    }, parent, 'icon')
end

function Icons.release()
    for name, image in pairs(cache) do
        image:release()
        cache[name] = nil
    end
end

return Icons
