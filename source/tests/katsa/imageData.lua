return function(T)
    local Image = require('source.katsa.image')
    local d = Image.newImageData(4, 3)
    d:setPixel(1, 2, 1, 0.5, 0.25, 1)
    local r, g, b, a = d:getPixel(1, 2)
    T.check(r == 1 and math.abs(g - 0.5) < 0.005 and math.abs(b - 0.25) < 0.005 and a == 1, 'rgba8 pixel roundtrip')
    d:mapPixel(function(x, y) return x / 3, y / 2, 0, 1 end)
    local _, g2 = d:getPixel(2, 2)
    T.check(math.abs(g2 - 1) < 0.005, 'mapPixel')
    local f = Image.newImageData(2, 2, 'rgba32f')
    f:setPixel(0, 0, 4.5, -2, 0.125, 1)
    local fr, fg, fb = f:getPixel(0, 0)
    T.check(fr == 4.5 and fg == -2 and fb == 0.125, 'rgba32f stores floats')
    local h = Image.newImageData(2, 2, 'rgba16f')
    h:setPixel(1, 1, 0.5, 2, -1.5, 1)
    local hr, hg, hb, ha = h:getPixel(1, 1)
    T.check(hr == 0.5 and hg == 2 and hb == -1.5 and ha == 1, 'rgba16f half float roundtrip')
    local c = d:clone(); c:setPixel(0, 0, 1, 1, 1, 1)
    local c0 = d:getPixel(0, 0)
    T.check(c0 == 0 and c:getString() ~= d:getString(), 'clone is independent')
    local big = Image.newImageData(8, 8); big:paste(d, 2, 2, 0, 0, 4, 3)
    local pr = big:getPixel(3, 2)
    T.check(math.abs(pr - 1 / 3) < 0.005, 'paste copies a region')
    T.check(not pcall(d.getPixel, d, 9, 9), 'out-of-range pixel errors')
    local png = d:encode('png')
    local back = Image.newImageData(png)
    T.check(back:getWidth() == 4 and back:getString() == d:getString(), 'png encode/decode roundtrip')
end
